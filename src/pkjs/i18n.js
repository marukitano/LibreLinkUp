function normalizeLocale(value) {
    return String(value || "")
        .trim()
        .replace(/_/g, "-")
        .toLowerCase();
}

function resolveLanguage(preference, phoneLocale) {
    var selected = normalizeLocale(preference);

    if (
        selected === "en" ||
        selected === "de" ||
        selected === "fr" ||
        selected === "it"
    ) {
        return selected;
    }

    var locale = normalizeLocale(phoneLocale);

    // German for DE, de-DE, de-CH, de-AT and even a country-only AT value.
    if (
        locale === "at" ||
        locale === "de" ||
        locale.indexOf("de-") === 0
    ) {
        return "de";
    }

    if (locale === "fr" || locale.indexOf("fr-") === 0) {
        return "fr";
    }

    if (locale === "it" || locale.indexOf("it-") === 0) {
        return "it";
    }

    return "en";
}

function translateValue(value, translations) {
    var tag = Object.prototype.toString.call(value);

    if (tag === "[object Array]") {
        return value.map(function (item) {
            return translateValue(item, translations);
        });
    }

    if (value && tag === "[object Object]") {
        var result = {};

        Object.keys(value).forEach(function (key) {
            result[key] = translateValue(
                value[key],
                translations
            );
        });

        return result;
    }

    if (
        typeof value === "string" &&
        Object.prototype.hasOwnProperty.call(
            translations,
            value
        )
    ) {
        return translations[value];
    }

    return value;
}

function localizeConfig(config, language) {
    var selected =
        CONFIG_TRANSLATIONS[language] ? language : "en";
    var translations =
        CONFIG_TRANSLATIONS[selected] || {};

    return translateValue(config, translations);
}

function getRuntimeStrings(language) {
    return (
        RUNTIME_TRANSLATIONS[language] ||
        RUNTIME_TRANSLATIONS.en
    );
}

